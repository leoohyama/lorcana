# 1. THE CHEF: R Data Processing (Runs Once)
# ==========================================
library(tidyverse)
library(DBI)
library(RPostgres)

# Load Dictionary & Fix Image Paths
master_dict <- read_csv("data/target_cards_with_epids2.csv", show_col_types = FALSE) %>%
  mutate(
    id = as.character(id), 
    tcgplayer_id = as.integer(tcgplayer_id), 
    cardname = paste(name, replace_na(version, ""), rarity, sep = " - "),
    folder_name = str_replace_all(set_name, "[ ']", "_"),
    image_path = paste0("data/enchanteds/images/", folder_name, "/", id, ".avif")
  ) %>%
  distinct(id, .keep_all = TRUE)

# Connect to Neon
con <- dbConnect(RPostgres::Postgres(), host = "ep-frosty-unit-amykrca9.c-5.us-east-1.aws.neon.tech", dbname = "neondb", user = "neondb_owner", password = Sys.getenv("NEON_PASSWORD"), port = 5432, sslmode = "require")

# Fetch Core Data
latest_prices <- dbGetQuery(con, "SELECT DISTINCT ON (tcgplayer_id) tcgplayer_id, market_price, pull_date FROM justtcg_prices ORDER BY tcgplayer_id, pull_date DESC")
past_prices <- dbGetQuery(con, "SELECT DISTINCT ON (tcgplayer_id) tcgplayer_id, market_price, pull_date FROM justtcg_prices WHERE pull_date <= CURRENT_DATE - INTERVAL '7 days' ORDER BY tcgplayer_id, pull_date DESC")
hist_data <- dbGetQuery(con, "SELECT tcgplayer_id, pull_date, market_price FROM justtcg_prices WHERE pull_date >= CURRENT_DATE - INTERVAL '365 days'")
chronos_pred <- dbGetQuery(con, "SELECT card_id as tcgplayer_id, target_date, pred_price, conf_low, conf_high, run_id FROM chronos_predictions")
gru_pred <- dbGetQuery(con, "SELECT card_id as tcgplayer_id, target_date, pred_price, run_id FROM gru_predictions")
metrics_df <- tryCatch(dbGetQuery(con, "SELECT tcgplayer_id, samp_ent_30d, hurst_30d, cv_30d, skewness_30d FROM card_ts_metrics"), error = function(e) data.frame())
dbDisconnect(con)

# --- Process Momentum ---
momentum <- latest_prices %>% 
  inner_join(past_prices, by = "tcgplayer_id", suffix = c("_cur", "_past")) %>% 
  mutate(pct = (market_price_cur - market_price_past)/market_price_past * 100, abs = market_price_cur - market_price_past) %>% 
  left_join(master_dict, by = "tcgplayer_id") %>% drop_na(cardname)

# Safety check: If momentum is empty, movers will be empty but won't crash R
if(nrow(momentum) > 0) {
  top_pct_g <- momentum %>% arrange(desc(pct)) %>% slice(1) %>% mutate(Category = "Top % Gainer")
  top_pct_l <- momentum %>% arrange(pct) %>% slice(1) %>% mutate(Category = "Top % Loser")
  top_abs_g <- momentum %>% arrange(desc(abs)) %>% slice(1) %>% mutate(Category = "Top $ Gainer")
  top_abs_l <- momentum %>% arrange(abs) %>% slice(1) %>% mutate(Category = "Top $ Loser")
  movers <- bind_rows(top_pct_g, top_pct_l, top_abs_g, top_abs_l)
} else {
  movers <- data.frame()
}

# --- Process Forecasts for Plotting ---
max_c_run <- if(nrow(chronos_pred) > 0) max(chronos_pred$run_id, na.rm=TRUE) else 0
max_g_run <- if(nrow(gru_pred) > 0) max(gru_pred$run_id, na.rm=TRUE) else 0

forecast_flat <- bind_rows(
  chronos_pred %>% mutate(tcgplayer_id = as.integer(tcgplayer_id)) %>% left_join(master_dict, by = "tcgplayer_id") %>% mutate(model = "Chronos", is_shadow = ifelse(run_id == max_c_run, FALSE, TRUE)) %>% select(cardname, date = target_date, model, price = pred_price, conf_low, conf_high, is_shadow, run_id),
  gru_pred %>% mutate(tcgplayer_id = as.integer(tcgplayer_id)) %>% left_join(master_dict, by = "tcgplayer_id") %>% mutate(model = "GRU", is_shadow = ifelse(run_id == max_g_run, FALSE, TRUE), conf_low = NA, conf_high = NA) %>% select(cardname, date = target_date, model, price = pred_price, conf_low, conf_high, is_shadow, run_id)
) %>% mutate(date = as.character(date)) %>% drop_na(cardname)

hist_flat <- hist_data %>% left_join(master_dict, by = "tcgplayer_id") %>% select(cardname, date = pull_date, price = market_price) %>% mutate(date = as.character(date)) %>% drop_na(cardname)

# --- Process Deeper Dive Data ---
if(nrow(metrics_df) > 0) metrics_df$tcgplayer_id <- as.integer(metrics_df$tcgplayer_id)
unified <- master_dict %>% 
  left_join(latest_prices %>% rename(current_price = market_price), by="tcgplayer_id") %>%
  left_join(metrics_df, by="tcgplayer_id")

# --- Find the Most Expensive Card ---
top_card <- unified %>% 
  drop_na(current_price) %>% 
  arrange(desc(current_price)) %>% 
  slice(1) %>% 
  pull(cardname)

if(length(top_card) == 0) top_card <- "Stitch - Carefree Surfer - Enchanted"

# Transfer to JavaScript
ojs_define(
  ojs_movers = movers,
  ojs_hist = hist_flat,
  ojs_forecast = forecast_flat,
  ojs_info = unified,
  ojs_cards = sort(unique(master_dict$cardname)),
  ojs_sets = c("All Sets", sort(unique(master_dict$set_name))),
  ojs_default_card = top_card
)
